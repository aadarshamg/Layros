import { defineField, defineType } from "sanity";

export default defineType({
  name: "order",
  title: "Order",
  type: "document",
  fields: [
    defineField({ name: "orderNumber", title: "Order number", type: "string", validation: (Rule) => Rule.required() }),
    defineField({
      name: "paymentMethod",
      title: "Payment method",
      type: "string",
      options: { list: [{ title: "Online (Razorpay)", value: "razorpay" }, { title: "Cash on Delivery", value: "cod" }] },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "paymentStatus",
      title: "Payment status",
      type: "string",
      options: { list: [{ title: "Paid", value: "paid" }, { title: "Pending (COD)", value: "pending" }, { title: "Failed", value: "failed" }] },
      initialValue: "pending",
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "fulfillmentStatus",
      title: "Fulfillment status",
      type: "string",
      options: { list: ["Unfulfilled", "Processing", "Shipped", "Delivered", "Cancelled", "Returned"] },
      initialValue: "Unfulfilled",
      description: "Updated automatically from Shiprocket tracking once the order ships.",
    }),
    defineField({ name: "razorpayOrderId", title: "Razorpay order ID", type: "string" }),
    defineField({ name: "razorpayPaymentId", title: "Razorpay payment ID", type: "string" }),
    defineField({
      name: "customer",
      title: "Customer account",
      description: "Set only when the order was placed while logged in — guest orders leave this empty.",
      type: "reference",
      to: [{ type: "customer" }],
      weak: true,
    }),
    defineField({ name: "customerEmail", title: "Customer email", type: "string" }),
    defineField({ name: "customerPhone", title: "Customer phone", type: "string" }),
    defineField({
      name: "shippingAddress",
      title: "Shipping address",
      type: "object",
      fields: [
        defineField({ name: "fullName", title: "Full name", type: "string" }),
        defineField({ name: "addressLine1", title: "Address line 1", type: "string" }),
        defineField({ name: "addressLine2", title: "Address line 2", type: "string" }),
        defineField({ name: "city", title: "City", type: "string" }),
        defineField({ name: "state", title: "State", type: "string" }),
        defineField({ name: "postalCode", title: "PIN code", type: "string" }),
        defineField({ name: "country", title: "Country", type: "string", initialValue: "IN" }),
      ],
    }),
    defineField({
      name: "items",
      title: "Items",
      type: "array",
      of: [
        {
          type: "object",
          name: "orderItem",
          fields: [
            defineField({ name: "title", title: "Title", type: "string" }),
            defineField({ name: "sku", title: "SKU", type: "string" }),
            defineField({ name: "sizeLabel", title: "Size", type: "string" }),
            defineField({ name: "unitPrice", title: "Unit price (INR)", type: "number" }),
            defineField({ name: "quantity", title: "Quantity", type: "number" }),
          ],
          preview: {
            select: { title: "title", quantity: "quantity", unitPrice: "unitPrice" },
            prepare({ title, quantity, unitPrice }) {
              return { title, subtitle: `× ${quantity} @ ₹${unitPrice}` };
            },
          },
        },
      ],
    }),
    defineField({ name: "subtotalAmount", title: "Subtotal before discount (INR)", type: "number" }),
    defineField({ name: "couponCode", title: "Coupon code used", type: "string" }),
    defineField({ name: "discountAmount", title: "Discount applied (INR)", type: "number" }),
    defineField({ name: "totalAmount", title: "Total (INR)", type: "number", validation: (Rule) => Rule.required().min(0) }),
    defineField({ name: "giftWrap", title: "Gift wrap requested", type: "boolean", description: "The shopper ticked complimentary gift wrap at checkout." }),
    defineField({ name: "giftWrapMessage", title: "Gift wrap message", type: "text", rows: 2 }),
    defineField({
      name: "shiprocketSyncStatus",
      title: "Sent to Shiprocket",
      type: "string",
      readOnly: true,
      options: { list: [{ title: "Sending…", value: "sending" }, { title: "Sent", value: "sent" }, { title: "Failed (retrying)", value: "failed" }] },
      description: "Website orders are sent to Shiprocket automatically. Failed sends are retried by /api/cron/shiprocket-retry.",
    }),
    defineField({ name: "shiprocketError", title: "Shiprocket error", type: "text", rows: 2, readOnly: true, hidden: ({ document }) => !document?.shiprocketError }),
    defineField({ name: "shiprocketOrderId", title: "Shiprocket order ID", type: "string", readOnly: true }),
    defineField({ name: "shiprocketShipmentId", title: "Shiprocket shipment ID", type: "string", readOnly: true }),
    defineField({ name: "shiprocketStatus", title: "Shiprocket status", type: "string", readOnly: true }),
    defineField({ name: "courierName", title: "Courier", type: "string", readOnly: true }),
    defineField({ name: "awbCode", title: "AWB (tracking number)", type: "string", readOnly: true }),
    defineField({ name: "trackingUrl", title: "Tracking link", type: "url", readOnly: true }),
    defineField({ name: "estimatedDelivery", title: "Estimated delivery", type: "string", readOnly: true }),
    defineField({ name: "lastTrackingUpdateAt", title: "Last tracking update", type: "datetime", readOnly: true }),
    defineField({ name: "lastShiprocketCheckAt", title: "Last checked with Shiprocket", type: "datetime", readOnly: true, hidden: true }),
    defineField({
      name: "confirmedBy",
      title: "Confirmed by",
      type: "string",
      readOnly: true,
      description: "browser = the shopper's checkout page confirmed the payment · webhook = Razorpay confirmed it directly (e.g. the shopper closed the page right after paying).",
    }),
  ],
  preview: {
    select: { orderNumber: "orderNumber", status: "paymentStatus", amount: "totalAmount", method: "paymentMethod" },
    prepare({ orderNumber, status, amount, method }) {
      return { title: orderNumber, subtitle: `₹${amount} · ${method} · ${status}` };
    },
  },
});
